const LANGUAGES: Record<string, Strings> = { en, de };

export function language(hass: HomeAssistant | undefined): string {
  const lang = (hass?.locale?.language ?? hass?.language ?? "en").slice(0, 2);
  return lang in LANGUAGES ? lang : "en";
}

export function localize(
  hass: HomeAssistant | undefined,
  key: string,
  vars: Record<string, unknown> = {},
): string {
  const lang = language(hass);
  const template = LANGUAGES[lang]?.[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? formatVar(vars[name], lang) : match,
  );
}

/** Pick "<key>.one" or "<key>.other" by the language's plural rules. */
export function plural(hass: HomeAssistant | undefined, key: string, count: number): string {
  const form = new Intl.PluralRules(language(hass)).select(count) === "one" ? "one" : "other";
  return localize(hass, `${key}.${form}`, { count });
}

function formatVar(value: unknown, lang: string): string {
  if (typeof value === "number") {
    return new Intl.NumberFormat(lang, { maximumFractionDigits: 1 }).format(value);
  }
  return String(value);
}

export const TRANSLATIONS = LANGUAGES;
